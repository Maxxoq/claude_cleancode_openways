#!/usr/bin/env bash
# Builds the Claude Code plugin files from the single source prompt.
# Source of truth: prompt/clean-code-agent.md (+ prompt/claude-code-addendum.md)
# Run after editing the prompt:  ./scripts/build.sh
# Check mode for CI:             ./scripts/build.sh --check
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROMPT="$ROOT/prompt/clean-code-agent.md"
ADDENDUM="$ROOT/prompt/claude-code-addendum.md"
PLUGIN="$ROOT/plugins/cleancode"
AGENT_OUT="$PLUGIN/agents/clean-code.md"
SKILL_OUT="$PLUGIN/skills/clean/SKILL.md"
HEADER="<!-- GENERATED by scripts/build.sh from prompt/ — do not edit by hand. -->"

build_agent() {
  cat <<'EOF'
---
name: clean-code
description: Clean Code Agent by OpenWays.ai. Audits and refactors a codebase end to end without changing behaviour — dead code, naming, duplication, structure, error handling, security hygiene, tests. Use when the user asks to clean up, refactor, tidy, or audit code quality.
model: inherit
color: green
---
EOF
  echo "$HEADER"
  echo
  cat "$PROMPT" "$ADDENDUM"
}

build_skill() {
  cat <<'EOF'
---
name: clean
description: Run the OpenWays.ai Clean Code Agent on this codebase — audit or refactor without changing behaviour. Modes are audit (report only), safe (default, low-risk fixes), deep (plan first, then structural refactors).
argument-hint: "[audit|safe|deep] [path or 'diff']"
disable-model-invocation: true
---
EOF
  echo "$HEADER"
  cat <<'EOF'

**Task:** Run the Clean Code Agent described below.

**Arguments:** `$ARGUMENTS`
- The first word, if it is `audit`, `safe`, or `deep`, is the mode. Otherwise the mode is `safe`.
- The rest is the scope: a path, a module, or `diff` (only files changed against the default branch, plus uncommitted changes). Empty means the whole repository.

Start with Phase 1. State the mode and scope you are using in your first message.

EOF
  cat "$PROMPT" "$ADDENDUM"
}

check=0
[[ "${1:-}" == "--check" ]] && check=1

status=0
for target in agent skill; do
  out_var="${target^^}_OUT"; out="${!out_var}"
  if (( check )); then
    if ! diff -q <("build_$target") "$out" >/dev/null 2>&1; then
      echo "out of date: ${out#"$ROOT"/} (run ./scripts/build.sh)"; status=1
    fi
  else
    mkdir -p "$(dirname "$out")"
    "build_$target" > "$out"
    echo "built ${out#"$ROOT"/}"
  fi
done
exit $status
